import { DatabaseSync } from 'node:sqlite';
import { mkdirSync,readFileSync } from 'node:fs';
import { dirname,resolve } from 'node:path';
import { cfg } from './config.js';

let db; let pool; let queue=Promise.resolve();
const translate = sql => { let n=0; return sql.replace(/\?/g,()=>`$${++n}`); };
function sqliteConn(){
  const path=resolve(cfg.path); mkdirSync(dirname(path),{recursive:true});
  db=new DatabaseSync(path); db.exec('PRAGMA foreign_keys=ON; PRAGMA busy_timeout=5000; PRAGMA journal_mode=WAL;');
  db.exec(readFileSync(new URL('../sql/sqlite.sql',import.meta.url),'utf8'));
  // Safe, incremental upgrade for existing v2.5 SQLite files.
  const cols=new Set(db.prepare('PRAGMA table_info(users)').all().map(c=>c.name));
  if(!cols.has('is_active'))db.exec('ALTER TABLE users ADD COLUMN is_active INTEGER NOT NULL DEFAULT 1 CHECK(is_active IN (0,1))');
  if(!cols.has('last_login_at'))db.exec('ALTER TABLE users ADD COLUMN last_login_at TEXT');
  if(!cols.has('access_role')){db.exec("ALTER TABLE users ADD COLUMN access_role TEXT NOT NULL DEFAULT 'rental_agent'");db.exec("UPDATE users SET access_role='admin' WHERE role='admin'");}
  if(!cols.has('customer_id'))db.exec('ALTER TABLE users ADD COLUMN customer_id INTEGER REFERENCES customers(id)');
  const bookingCols=new Set(db.prepare('PRAGMA table_info(bookings)').all().map(c=>c.name));
  if(!bookingCols.has('assigned_driver_id'))db.exec('ALTER TABLE bookings ADD COLUMN assigned_driver_id INTEGER REFERENCES users(id)');
  return {
    all:async(sql,params=[])=>db.prepare(sql).all(...params),
    one:async(sql,params=[])=>db.prepare(sql).get(...params)||null,
    exec:async(sql,params=[])=>db.prepare(sql).run(...params),
    transaction:async(fn)=>{
      let release;
      const prior=queue;
      queue=new Promise(resolve=>release=resolve);
      await prior;
      db.exec('BEGIN IMMEDIATE');
      try { const result=await fn({all:async(s,p=[])=>db.prepare(s).all(...p),one:async(s,p=[])=>db.prepare(s).get(...p)||null,exec:async(s,p=[])=>db.prepare(s).run(...p)});
        db.exec('COMMIT'); return result; }
      catch(e){db.exec('ROLLBACK');throw e;} finally{release();}
    },close:async()=>db.close()
  };
}
export async function connectDb(){
  if(cfg.driver==='sqlite') return sqliteConn();
  if(cfg.driver!=='postgres') throw Error('Unsupported DB_DRIVER');
  if(!cfg.databaseUrl) throw Error('Set DATABASE_URL for postgres');
  const {Pool}=await import('pg');
  pool=new Pool({connectionString:cfg.databaseUrl,ssl:process.env.DATABASE_SSL==='true'?{rejectUnauthorized:true}:undefined});
  await pool.query('SELECT 1');
  await pool.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE');
  await pool.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMPTZ');
  await pool.query("ALTER TABLE users ADD COLUMN IF NOT EXISTS access_role TEXT NOT NULL DEFAULT 'rental_agent'");
  await pool.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS customer_id INTEGER REFERENCES customers(id)');
  await pool.query('ALTER TABLE bookings ADD COLUMN IF NOT EXISTS assigned_driver_id INTEGER REFERENCES users(id)');
  await pool.query(`CREATE TABLE IF NOT EXISTS portal_notifications (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,customer_id INTEGER NOT NULL REFERENCES customers(id),kind TEXT NOT NULL,message TEXT NOT NULL,event_key TEXT UNIQUE NOT NULL,is_read BOOLEAN NOT NULL DEFAULT FALSE,created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`);
  await pool.query('CREATE INDEX IF NOT EXISTS idx_portal_notifications_customer ON portal_notifications(customer_id,id)');
  await pool.query(`CREATE TABLE IF NOT EXISTS cancellation_requests (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id),customer_id INTEGER NOT NULL REFERENCES customers(id),refund_due DOUBLE PRECISION NOT NULL DEFAULT 0,refund_status TEXT NOT NULL DEFAULT 'none' CHECK (refund_status IN ('none','manual_review','resolved')),created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`);
  await pool.query("UPDATE users SET access_role='admin' WHERE role='admin' AND access_role='rental_agent'");
  return {
    all:async(sql,p=[])=>(await pool.query(translate(sql),p)).rows,
    one:async(sql,p=[])=> (await pool.query(translate(sql),p)).rows[0]||null,
    exec:async(sql,p=[])=>pool.query(translate(sql),p),
    transaction:async(fn)=>{const client=await pool.connect();try{await client.query('BEGIN');const conn={
      all:async(s,p=[]) =>(await client.query(translate(s),p)).rows,
      one:async(s,p=[]) =>(await client.query(translate(s),p)).rows[0]||null,
      exec:async(s,p=[])=>client.query(translate(s),p)
    };const out=await fn(conn);await client.query('COMMIT');return out;}catch(e){await client.query('ROLLBACK');throw e;}finally{client.release();}},close:async()=>pool.end()
  };
}
