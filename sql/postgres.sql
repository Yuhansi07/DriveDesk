-- Run against an empty PostgreSQL database. DriveDesk Pro schema.
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE TABLE IF NOT EXISTS users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN ('admin','staff')),
 access_role TEXT NOT NULL DEFAULT 'rental_agent', customer_id INTEGER,
 is_active BOOLEAN NOT NULL DEFAULT TRUE, last_login_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS vehicles (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 plate TEXT NOT NULL UNIQUE, make TEXT NOT NULL, model TEXT NOT NULL,
 category TEXT NOT NULL, year INTEGER NOT NULL, daily_rate DOUBLE PRECISION NOT NULL CHECK(daily_rate>0),
 seats INTEGER NOT NULL DEFAULT 5, mileage_km DOUBLE PRECISION NOT NULL DEFAULT 0,
 service_due_km DOUBLE PRECISION, insurance_expiry DATE,
 status TEXT NOT NULL DEFAULT 'available' CHECK(status IN ('available','maintenance')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS customers (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, phone TEXT NOT NULL, email TEXT,
 license_no TEXT NOT NULL, license_expiry DATE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS bookings (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id INTEGER NOT NULL REFERENCES vehicles(id), customer_id INTEGER NOT NULL REFERENCES customers(id),
 pickup_date DATE NOT NULL, return_date DATE NOT NULL,
 days INTEGER NOT NULL CHECK(days>=1), daily_rate DOUBLE PRECISION NOT NULL,
 total_amount DOUBLE PRECISION NOT NULL, status TEXT NOT NULL DEFAULT 'pending'
 CHECK(status IN ('pending','confirmed','active','completed','cancelled')),
 assigned_driver_id INTEGER REFERENCES users(id), pickup_code_hash TEXT, pickup_code_expires_at TIMESTAMPTZ,
 pickup_at TIMESTAMPTZ, returned_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CHECK(return_date > pickup_date)
);
-- database-level protection against double booking even under concurrent requests
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='no_overlapping_active_bookings') THEN
    ALTER TABLE bookings ADD CONSTRAINT no_overlapping_active_bookings
    EXCLUDE USING gist (vehicle_id WITH =, daterange(pickup_date, return_date, '[)') WITH &&)
    WHERE (status IN ('pending','confirmed','active'));
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS payments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id INTEGER NOT NULL REFERENCES bookings(id), amount DOUBLE PRECISION NOT NULL CHECK(amount>0),
 method TEXT NOT NULL, note TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS inspections (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id INTEGER NOT NULL REFERENCES bookings(id), phase TEXT NOT NULL CHECK(phase IN ('pickup','return')),
 image_ref TEXT, findings_json TEXT NOT NULL DEFAULT '[]',
 reviewer_note TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS location_events (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id INTEGER NOT NULL REFERENCES vehicles(id), latitude DOUBLE PRECISION NOT NULL,
 longitude DOUBLE PRECISION NOT NULL, source TEXT NOT NULL CHECK(source IN ('tracker','staff_manual','simulated')),
 consent_confirmed BOOLEAN NOT NULL, recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS notifications (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind TEXT NOT NULL, message TEXT NOT NULL, entity_key TEXT NOT NULL UNIQUE,
 is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS audits (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id INTEGER REFERENCES users(id), action TEXT NOT NULL, entity TEXT NOT NULL,
 entity_id INTEGER, detail TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_bookings_vehicle_dates ON bookings(vehicle_id,pickup_date,return_date);
CREATE INDEX IF NOT EXISTS idx_location_vehicle_time ON location_events(vehicle_id,recorded_at);

-- Link customer-portal logins to their own customer record.
ALTER TABLE users ADD CONSTRAINT users_customer_link_fk FOREIGN KEY (customer_id) REFERENCES customers(id);

-- Customer portal v2.8
CREATE TABLE IF NOT EXISTS portal_notifications (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,customer_id INTEGER NOT NULL REFERENCES customers(id),kind TEXT NOT NULL,message TEXT NOT NULL,event_key TEXT UNIQUE NOT NULL,is_read BOOLEAN NOT NULL DEFAULT FALSE,created_at TIMESTAMPTZ NOT NULL DEFAULT NOW());
CREATE INDEX IF NOT EXISTS idx_portal_notifications_customer ON portal_notifications(customer_id,id);
CREATE TABLE IF NOT EXISTS cancellation_requests (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(id),customer_id INTEGER NOT NULL REFERENCES customers(id),refund_due DOUBLE PRECISION NOT NULL DEFAULT 0,refund_status TEXT NOT NULL DEFAULT 'none' CHECK (refund_status IN ('none','manual_review','resolved')),created_at TIMESTAMPTZ NOT NULL DEFAULT NOW());
